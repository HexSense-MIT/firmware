uint32_t generate_crc( const uint8_t* buf, int len )
{
    uint32_t crc = 0xFFFFFFFF;
    uint32_t mask;

    while( len-- > 0 )
    {
        crc = crc ^ *buf++;
        for( int i = 0; i < 8; i++ )
        {
            mask = -( crc & 1 );
            crc  = ( crc >> 1 ) ^ ( 0xEDB88320 & mask );
        }
    }
    return ~crc;
}
